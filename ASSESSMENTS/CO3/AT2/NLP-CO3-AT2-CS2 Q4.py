# Q8: Role of POS Tags

word = "book"

sentence1_tag = "VB"
sentence2_tag = "NN"

print("Word:", word)

print()
print("Sentence 1: Book a flight ticket now.")
print("POS Tag:", sentence1_tag)
print("Meaning: Action / Booking request")
print("Possible Intent: Flight Booking")

print()
print("Sentence 2: This book is interesting.")
print("POS Tag:", sentence2_tag)
print("Meaning: Object / Noun")
print("Possible Intent: General Information")

print()
print("POS tagging helps the chatbot to:")
print("1. Understand grammatical roles")
print("2. Resolve ambiguity")
print("3. Identify user intent")
print("4. Generate better responses")
print("5. Improve language understanding")
