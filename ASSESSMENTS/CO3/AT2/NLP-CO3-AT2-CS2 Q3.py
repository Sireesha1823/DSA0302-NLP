# Q7: Compare Rule-Based and HMM Tagging

print("RULE-BASED TAGGING")
print("-------------------")
print("Uses manually created linguistic rules.")
print("Easy to understand.")
print("Works well for known patterns.")
print("Difficult to maintain for very large systems.")

print()

print("HMM / STOCHASTIC TAGGING")
print("------------------------")
print("Uses probabilities learned from training data.")
print("Handles ambiguity using probability.")
print("More suitable for large datasets.")
print("Can adapt to different language patterns.")

print()

print("CONCLUSION:")
print("HMM tagging is more suitable for large-scale chatbot deployment.")
print("A hybrid system can combine rules and statistical models.")
